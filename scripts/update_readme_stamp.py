REPO_ROOT = SCRIPT_DIR.parent

README_PATH = REPO_ROOT / "Readme.md"
TIMEZONE = ZoneInfo("Europe/Berlin")
START_MARKER = "<!-- AUTO_DOCS_CONTENT_START -->"
END_MARKER = "<!-- AUTO_DOCS_CONTENT_END -->"

